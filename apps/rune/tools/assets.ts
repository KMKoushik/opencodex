// Regenerate shared vector assets without a runtime dependency on the web UI.
import * as icons from '../../web/node_modules/@hugeicons/core-free-icons';
import { readFile, writeFile } from 'node:fs/promises';
import { GLYPHS } from '../../web/src/features/apps/app-glyphs';
import { CANVAS_GLYPH_GROUPS } from '../../../packages/contracts/src/canvas';
