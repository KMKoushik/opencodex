// Regenerate shared vector assets without a runtime dependency on the web UI.
import * as icons from '../../web/node_modules/@hugeicons/core-free-icons';
import { readFile, writeFile } from 'node:fs/promises';
const names = {
  back: 'ArrowLeft02Icon',
  forward: 'ArrowRight02Icon',
  down: 'ArrowDown01Icon',
  right: 'ArrowRight01Icon',
  sidebar: 'PanelLeftCloseIcon',
  edit: 'PencilEdit02Icon',
  search: 'Search01Icon',
  folder_open: 'FolderOpenIcon',
  tasks: 'CheckListIcon',
  apps: 'GridViewIcon',
  settings: 'Settings01Icon',
  usage: 'DashboardSpeed01Icon',
  folder: 'Folder01Icon',
  plus: 'PlusSignIcon',
  close: 'Cancel01Icon',
  inbox: 'InboxIcon',
  book: 'BookOpen01Icon',
  test: 'TestTube01Icon',
  changes: 'PlusMinusIcon',
  plan: 'LeftToRightListBulletIcon',
  up: 'ArrowUp02Icon',
  branch: 'GitBranchIcon',
  shield: 'Shield01Icon',
  worktree: 'FolderGit2Icon',
} as const satisfies Record<string, keyof typeof icons>;
const esc = (s: string) => s.replaceAll('&', '&amp;').replaceAll('"', '&quot;');
let src = '// Generated by tools/assets.ts from the web UI icon catalog.\nuse rune::Icon;\n';
for (const [id, name] of Object.entries(names)) {
  const data = icons[name];
  if (!data) throw new Error(name);
  const body = data
    .map(
      ([tag, props]) =>
        `<${tag} ${Object.entries(props)
          .filter(([k]) => k !== 'key')
          .map(
            ([k, v]) => `${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}="${esc(String(v))}"`,
          )
          .join(' ')}/>`,
    )
    .join('');
  src += `pub const ${id.toUpperCase()}: Icon = Icon { name: "${id}", view: 24.0, body: r##"<g fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${body}</g>"## };\n`;
}
await writeFile(new URL('../src/icons.rs', import.meta.url), src);
const brand = await readFile(
  new URL('../../web/src/features/brand/brand.tsx', import.meta.url),
  'utf8',
);
const paths = [...brand.matchAll(/className="wordmark-(open|codex)"\s+d="([^"]+)"/g)];
await writeFile(
  new URL('../assets/wordmark.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="5 -39 1017 174">${paths.map(([, role, d]) => `<path fill="${role === 'open' ? 'MUTED' : 'INK'}" d="${d}"/>`).join('')}</svg>`,
);
