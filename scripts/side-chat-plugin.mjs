import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

// The gateway installs the side-chat plugin into OpenCode as one self-contained file.
// Embed its transpiled source so browser, Node, and bundled Electron builds share it.
const input = new URL('../packages/side-chat-plugin/src/plugin.ts', import.meta.url);
const output = new URL('../packages/gateway/src/side-chat-plugin.generated.ts', import.meta.url);

const { outputText, diagnostics } = ts.transpileModule(readFileSync(input, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  reportDiagnostics: true,
});
if (diagnostics?.length) throw new Error('The side-chat plugin did not transpile.');
if (/^\s*import\s(?!type\b)/m.test(outputText) || /\brequire\(/.test(outputText))
  throw new Error('The side-chat plugin must not have runtime imports.');
const version = createHash('sha256').update(outputText).digest('hex').slice(0, 12);
const source = `// OpenCodex side-chat plugin ${version}. Installed by OpenCodex; edits are replaced.\n${outputText}`;
const generated = `// Generated by \`bun side-chat-plugin\` from packages/side-chat-plugin/src/plugin.ts. Do not edit.
export const SIDE_CHAT_PLUGIN = { version: ${JSON.stringify(version)}, source: ${JSON.stringify(source)} };
`;

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    console.error('The embedded side-chat plugin is stale. Run `bun side-chat-plugin`.');
    process.exit(1);
  }
  console.log('Embedded side-chat plugin is current.');
} else {
  writeFileSync(output, generated);
  console.log(`Embedded side-chat plugin ${version}.`);
}
