import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import ts from 'typescript';

// Builds what the gateway serves and checks canvases with: the sandboxed frame runtime,
// the server-render bundle for canvas_check, the child-process host for canvas servers,
// and the type files canvases compile against.
// The output is generated (not committed) so packaged builds carry it without node_modules.
const root = fileURLToPath(new URL('..', import.meta.url));
const sdk = join(root, 'packages/canvas');
const output = join(root, 'packages/gateway/src');

async function bundle(entry, platform = 'browser') {
  const result = await build({
    entryPoints: [join(sdk, 'src', entry)],
    bundle: true,
    write: false,
    format: platform === 'node' ? 'cjs' : 'iife',
    platform,
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    jsx: 'automatic',
    loader: { '.css': 'text' },
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  return result.outputFiles[0].text;
}

/** Declarations of the SDK, keyed by file name. */
function sdkDeclarations() {
  const files = {};
  const program = ts.createProgram([join(sdk, 'src/index.ts'), join(sdk, 'src/server.ts')], {
    declaration: true,
    emitDeclarationOnly: true,
    jsx: ts.JsxEmit.ReactJSX,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    target: ts.ScriptTarget.ES2022,
    lib: ['lib.es2022.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'],
    strict: true,
    skipLibCheck: true,
    types: [],
    outDir: '/sdk',
    rootDir: join(sdk, 'src'),
  });
  const result = program.emit(undefined, (name, text) => {
    files[name.replace(/^\/sdk\//, '')] = text;
  });
  const errors = ts
    .getPreEmitDiagnostics(program)
    .concat(result.diagnostics)
    .filter((item) => item.category === ts.DiagnosticCategory.Error);
  if (errors.length)
    throw new Error(ts.formatDiagnostics(errors, ts.createCompilerHost({})).slice(0, 4000));
  return files;
}

/** Library files reachable from the libs canvases compile with. */
function libraries() {
  const directory = dirname(createRequire(import.meta.url).resolve('typescript/lib/lib.d.ts'));
  const files = {};
  const pending = ['lib.es2022.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'];
  while (pending.length) {
    const name = pending.pop();
    if (files[name]) continue;
    files[name] = readFileSync(join(directory, name), 'utf8');
    for (const [, lib] of files[name].matchAll(/<reference lib="([^"]+)"/g))
      pending.push(`lib.${lib.toLowerCase()}.d.ts`);
  }
  return files;
}

/** A package's top-level declaration files and package.json. */
function packageTypes(name, from) {
  const manifest = createRequire(from).resolve(`${name}/package.json`);
  const directory = dirname(manifest);
  const files = { 'package.json': readFileSync(manifest, 'utf8') };
  for (const file of readdirSync(directory))
    if (file.endsWith('.d.ts')) files[file] = readFileSync(join(directory, file), 'utf8');
  return { files, manifest };
}

const [runtime, ssr, serverHost] = await Promise.all([
  bundle('runtime.tsx'),
  bundle('ssr.tsx'),
  bundle('server-host.ts', 'node'),
]);
const react = packageTypes('@types/react', join(sdk, 'package.json'));
const csstype = packageTypes('csstype', react.manifest);
const types = {};
for (const [file, text] of Object.entries(libraries())) types[`/lib/${file}`] = text;
for (const [file, text] of Object.entries(react.files))
  types[`/node_modules/@types/react/${file}`] = text;
for (const [file, text] of Object.entries(csstype.files))
  types[`/node_modules/csstype/${file}`] = text;
for (const [file, text] of Object.entries(sdkDeclarations()))
  types[`/node_modules/@opencodex/canvas/${file}`] = text;
types['/node_modules/@opencodex/canvas/package.json'] = JSON.stringify({
  name: '@opencodex/canvas',
  types: 'index.d.ts',
});

const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 12);
const header = '// Generated by `bun canvas` from packages/canvas. Do not edit.\n';
writeFileSync(
  join(output, 'canvas-runtime.generated.ts'),
  `${header}export const CANVAS_RUNTIME = { version: ${JSON.stringify(hash(runtime))}, source: ${JSON.stringify(runtime)} };\nexport const CANVAS_SSR = ${JSON.stringify(ssr)};\nexport const CANVAS_SERVER_HOST = ${JSON.stringify(serverHost)};\n`,
);
const typesText = JSON.stringify(types);
writeFileSync(
  join(output, 'canvas-types.generated.ts'),
  `${header}export const CANVAS_TYPES_VERSION = ${JSON.stringify(hash(typesText))};\nexport const CANVAS_TYPES: Record<string, string> = ${typesText};\n`,
);
console.log(
  `Built canvas runtime (${Math.round(runtime.length / 1024)} KB), SSR (${Math.round(ssr.length / 1024)} KB), types (${Math.round(typesText.length / 1024)} KB).`,
);
