import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { build } from 'bun';

// Like the side-chat plugin, this is installed as a single file on the OpenCode
// host. Bundle the pinned bridge; the gateway never imports or runs its runtime.
const root = new URL('../packages/claude-code-plugin/', import.meta.url);
const dependency = createRequire(
  realpathSync(
    new URL('node_modules/@khalilgharbaoui/opencode-claude-code-plugin/dist/index.js', root),
  ),
);
const jsonc = dirname(dependency.resolve('jsonc-parser/package.json'));
const result = await build({
  entrypoints: [fileURLToPath(new URL('src/plugin.ts', root))],
  target: 'node',
  format: 'esm',
  minify: true,
  // The UMD entry hides relative require() calls behind a factory parameter.
  // Bundle the package's ESM entry so the installed file has no adjacent deps.
  plugins: [
    {
      name: 'jsonc-esm',
      setup(builder) {
        builder.onResolve({ filter: /^jsonc-parser$/ }, () => ({
          path: join(jsonc, 'lib/esm/main.js'),
        }));
      },
    },
  ],
});
if (!result.success)
  throw new AggregateError(result.logs, 'Could not bundle the Claude Code plugin.');
const notices = [
  [
    'Claude Code bridge',
    new URL('node_modules/@khalilgharbaoui/opencode-claude-code-plugin/LICENSE', root),
  ],
  ['jsonc-parser', join(jsonc, 'LICENSE.md')],
]
  .map(([name, path]) => `${name}\n${readFileSync(path, 'utf8')}`)
  .join('\n\n');
const body = `/*\n${notices.replaceAll('*/', '* /')}\n*/\n${await result.outputs[0].text()}`;
const version = createHash('sha256').update(body).digest('hex').slice(0, 12);
const source = `// OpenCodex Claude Code plugin ${version}. Installed by OpenCodex; edits are replaced.\n${body}`;
const output = new URL('../packages/gateway/src/claude-code-plugin.generated.ts', import.meta.url);
// Electron's CommonJS shim transform rewrites import.meta even inside source
// strings. Encode the artifact so that only OpenCode ever transforms its code.
const generated = `// Generated by \`bun claude-code-plugin\`. Do not edit.\nexport const CLAUDE_CODE_PLUGIN = { version: ${JSON.stringify(version)}, source: Buffer.from(${JSON.stringify(Buffer.from(source).toString('base64'))}, 'base64').toString('utf8') };\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    throw new Error('The embedded Claude Code plugin is stale. Run bun claude-code-plugin.');
  }
  console.log('Embedded Claude Code plugin is current.');
} else {
  writeFileSync(output, generated);
  console.log(`Embedded Claude Code plugin ${version} (${source.length} bytes).`);
}
